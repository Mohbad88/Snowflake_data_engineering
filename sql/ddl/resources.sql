CREATE FILE FORMAT IF NOT EXISTS AIRBNB.STAGING.AIRBNB_CSV
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS AIRBNB.STAGING.AIRBNB_FILES
  FILE_FORMAT = (FORMAT_NAME = 'AIRBNB.STAGING.AIRBNB_CSV');

-- Déposer bookings.csv, hosts.csv et listings.csv dans le stage avant de lancer ces commandes.
COPY INTO AIRBNB.STAGING.BOOKINGS
  FROM @AIRBNB.STAGING.AIRBNB_FILES
  FILES = ('bookings.csv')
  FILE_FORMAT = (FORMAT_NAME = 'AIRBNB.STAGING.AIRBNB_CSV')
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO AIRBNB.STAGING.HOSTS
  FROM @AIRBNB.STAGING.AIRBNB_FILES
  FILES = ('hosts.csv')
  FILE_FORMAT = (FORMAT_NAME = 'AIRBNB.STAGING.AIRBNB_CSV')
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO AIRBNB.STAGING.LISTINGS
  FROM @AIRBNB.STAGING.AIRBNB_FILES
  FILES = ('listings.csv')
  FILE_FORMAT = (FORMAT_NAME = 'AIRBNB.STAGING.AIRBNB_CSV')
  ON_ERROR = 'ABORT_STATEMENT';
